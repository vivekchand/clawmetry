def _write_jsonl(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(json.dumps(r) for r in rows) + "\n")
    return path


# ── derive_title_from_jsonl: the pinned derivation rule ───────────────────────


def test_plain_user_string(tmp_path):
    p = _write_jsonl(tmp_path / "s.jsonl", [
        {"type": "user", "message": {"role": "user", "content":
         "bump clawmetry cloud to use the latest version of clawmetry oss"}},
        {"type": "assistant", "message": {"role": "assistant", "content": "ok"}},
    ])
    assert st.derive_title_from_jsonl(p) == (
        "bump clawmetry cloud to use the latest version of clawmetry oss"
    )


def test_list_content_blocks(tmp_path):
    p = _write_jsonl(tmp_path / "s.jsonl", [
        {"type": "user", "message": {"role": "user", "content": [
            {"type": "tool_result", "content": "not a title"},
            {"type": "text", "text": "fix the flaky ci matrix"},
        ]}},
    ])
    assert st.derive_title_from_jsonl(p) == "fix the flaky ci matrix"


def test_skips_angle_bracket_and_caveat_texts(tmp_path):
    p = _write_jsonl(tmp_path / "s.jsonl", [
        {"type": "user", "message": {"content": "<system-reminder>stuff</system-reminder>"}},
        {"type": "user", "message": {"content": "<command-name>/clear</command-name>"}},
        {"type": "user", "message": {"content":
         "Caveat: the messages below were generated by the user while running..."}},
        {"type": "user", "message": {"content": "   "}},
        {"type": "user", "message": {"content": "the real first prompt"}},
    ])
    assert st.derive_title_from_jsonl(p) == "the real first prompt"


def test_truncates_to_80_chars_with_ellipsis(tmp_path):
    long = "word " * 40  # 200 chars once collapsed
    p = _write_jsonl(tmp_path / "s.jsonl", [
        {"type": "user", "message": {"content": long}},
    ])
    out = st.derive_title_from_jsonl(p)
    assert out.endswith("…")
    assert len(out) <= 80
    assert out.startswith("word word")


def test_collapses_whitespace(tmp_path):
    p = _write_jsonl(tmp_path / "s.jsonl", [
        {"type": "user", "message": {"content": "  hello\n\n   world\t! "}},
    ])
    assert st.derive_title_from_jsonl(p) == "hello world !"


def test_empty_file_no_title(tmp_path):
    p = tmp_path / "empty.jsonl"
    p.write_text("")
    assert st.derive_title_from_jsonl(p) == ""


def test_missing_file_never_raises(tmp_path):
    assert st.derive_title_from_jsonl(tmp_path / "nope.jsonl") == ""


def test_non_json_lines_skipped(tmp_path):
    p = tmp_path / "s.jsonl"
    p.write_text('not json\n{"type": "user", "message": {"content": "hi there"}}\n')
    assert st.derive_title_from_jsonl(p) == "hi there"


# ── event-based derivation (codex/cursor/… ride the same ingest path) ─────────


def _ev(role, content, i=0):
    return Event(agent="x", session_id="s", id=f"e{i}", type="message",
                 ts=float(i), role=role, content=content)


def test_events_prefer_user_role():
    evs = [_ev("assistant", "I will start by reading the file", 0),
           _ev("user", "add a dark mode toggle", 1)]
    assert st.derive_title_from_family_events(evs) == "add a dark mode toggle"


def test_events_skip_plumbing_texts():
    evs = [_ev("user", "<local-command-stdout>ok</local-command-stdout>", 0),
           _ev("user", "Caveat: resumed session preamble", 1),
           _ev("user", "ship the release notes", 2)]
    assert st.derive_title_from_family_events(evs) == "ship the release notes"


def test_events_roleless_fallback():
    # Adapters that don't stamp roles keep their legacy any-text titling.
    evs = [_ev("", "investigate the login timeout", 0)]
    assert st.derive_title_from_family_events(evs) == "investigate the login timeout"


def test_events_empty_never_raises():
    assert st.derive_title_from_family_events([]) == ""
    assert st.derive_title_from_family_events(None) == ""


# ── looks_like_session_id (the no-clobber discriminator) ─────────────────────


def test_id_like_titles():
    uuid = "e149acae-1a2b-4c3d-8e9f-0a1b2c3d4e5f"
    assert st.looks_like_session_id("", "x")
    assert st.looks_like_session_id(uuid, f"claude_code:{uuid}")
    assert st.looks_like_session_id(f"claude_code:{uuid}", f"claude_code:{uuid}")
    # sid[:40] truncation (what the list path stores as "name")
    assert st.looks_like_session_id(f"claude_code:{uuid}"[:40], f"claude_code:{uuid}")
    assert not st.looks_like_session_id("fix the flaky ci matrix", f"claude_code:{uuid}")


