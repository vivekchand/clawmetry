def _msg_event(event_id, sid, role, content, ts):
    return {
        "id": event_id, "node_id": "n", "agent_id": "main", "session_id": sid,
        "event_type": "message", "ts": ts,
        "data": json.dumps({"role": role, "content": content, "timestamp": ts}),
    }


def test_transcripts_serve_family_titles(transcripts_app):
    a, ls, tmp_path = transcripts_app
    store = ls.get_store()
    sid1 = f"claude_code:{_UUID1}"  # titled via the sessions-table join
    sid2 = f"claude_code:{_UUID2}"  # titled via the planted-JSONL fallback

    store.ingest(_msg_event("t1", sid1, "user", "hi", "2026-07-30T10:00:00Z"))
    store.ingest(_msg_event("t2", sid2, "user", "hi", "2026-07-30T11:00:00Z"))
    store.ingest_session({"session_id": sid1, "title": "wire the usage anomaly chart",
                          "started_at": "2026-07-30T10:00:00Z",
                          "last_active_at": "2026-07-30T10:00:00Z"})
    # sid2's stored title is the legacy UUID fallback — must NOT be served.
    store.ingest_session({"session_id": sid2, "title": _UUID2,
                          "started_at": "2026-07-30T11:00:00Z",
                          "last_active_at": "2026-07-30T11:00:00Z"})
    _write_jsonl(
        tmp_path / "claude" / "projects" / "-tmp-proj" / f"{_UUID2}.jsonl",
        [{"type": "user", "message": {"content": "refactor the cron health summary"}}],
    )
    store._flush_now()
    _wait_for_flush(store)

    body = a.test_client().get("/api/transcripts").get_json()
    assert body.get("_source") == "local_store"
    by_id = {t["id"]: t for t in body["transcripts"]}
    assert by_id[sid1]["title"] == "wire the usage anomaly chart"
    assert by_id[sid2]["title"] == "refactor the cron health summary"
