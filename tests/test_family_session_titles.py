def _wait_for_flush(store, timeout=3.0):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if store.health()["ring_depth"] == 0:
            return
        time.sleep(0.02)


def test_planted_jsonl_yields_titled_session_row(isolated_sync):
    """Events carry only plumbing text, but the planted ~/.claude transcript
    head titles the session row (the ground-truth path)."""
    sync, ls, tmp_path = isolated_sync
    _write_jsonl(
        tmp_path / "claude" / "projects" / "-tmp-proj" / f"{_UUID1}.jsonl",
        [
            {"type": "user", "message": {"content": "<command-name>/model</command-name>"}},
            {"type": "user", "message": {"content":
             "bump clawmetry cloud to use the latest version of clawmetry oss"}},
        ],
    )
    sessions = [Session(agent="claude_code", id=_UUID1, started_at=1000.0,
                        ended_at=1010.0, message_count=1)]
    events = {_UUID1: [_ev("user", "<system-reminder>plumbing</system-reminder>", 0)]}
    with patch.object(sync, "_family_adapter_classes",
                      lambda: [_fake_cc_adapter(sessions, events)]), \
         patch.object(sync, "_sync_allowed", return_value=True), \
         patch.object(sync, "_post", return_value={}):
        sync.sync_family_runtimes({"node_id": "n", "api_key": None}, {}, {})
    store = ls.get_store()
    _wait_for_flush(store)
    rows = store._fetch(
        "SELECT title FROM sessions WHERE session_id = ?",
        [f"claude_code:{_UUID1}"],
    )
    assert rows, "session row missing"
    assert rows[0][0] == (
        "bump clawmetry cloud to use the latest version of clawmetry oss"
    )


def test_ingest_never_clobbers_real_title(isolated_sync):
    """A re-ingest pass with nothing derivable must keep the existing human
    title (the legacy s.id fallback used to overwrite it with a UUID)."""
    sync, ls, _tmp = isolated_sync
    store = ls.get_store()
    sid = f"claude_code:{_UUID2}"
    store.ingest_session({"session_id": sid, "title": "a real human title",
                          "started_at": "2026-07-30T00:00:00Z"})
    sessions = [Session(agent="claude_code", id=_UUID2, started_at=1000.0,
                        ended_at=1010.0, message_count=1)]
    events = {_UUID2: [_ev("user", "<system-reminder>plumbing</system-reminder>", 0)]}
    with patch.object(sync, "_family_adapter_classes",
                      lambda: [_fake_cc_adapter(sessions, events)]), \
         patch.object(sync, "_sync_allowed", return_value=True), \
         patch.object(sync, "_post", return_value={}):
        sync.sync_family_runtimes({"node_id": "n", "api_key": None}, {}, {})
    _wait_for_flush(store)
    rows = store._fetch(
        "SELECT title FROM sessions WHERE session_id = ?", [sid])
    assert rows and rows[0][0] == "a real human title"


