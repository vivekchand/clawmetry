"""Family-runtime session titles from the first real user prompt.

Founder report 2026-07-30: the Conversations tab showed "Untitled session"
for every Claude Code session — ``/api/transcripts`` returned
``{id: "claude_code:UUID", title: ""}`` because (a) the list fast path
re-derived titles from the OpenClaw sessions dir (where family transcripts
don't live) and never read the ingest-persisted ``sessions.title``, and
(b) the ingest-side derivation missed list-block content / the "Caveat:"
resume preamble and clobbered real titles with the raw UUID fallback.

Pins the derivation rule in ``clawmetry/session_titles.py`` (first
qualifying user text; skip "<"-prefixed + "Caveat:" + empty; collapse
whitespace; 80-char cap with ellipsis) and the two consumer paths:
``sync.sync_family_runtimes`` (title persisted on the session row,
no-clobber) and ``/api/transcripts`` (titles actually served).
"""

